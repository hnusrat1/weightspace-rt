    print("claims: total", len(o["claims"]), "| true", sum(c["true"] for c in o["claims"]),
          "| false", [(c["run"], c["model"].split("-")[1], c["flaw"], round(c["targeted_rate"] or 0, 2), (c["condition"] or "")[:70]) for c in o["claims"] if not c["true"]])
    print("healthy runs:")
    for h in o["healthy"]:
        print("  ", h)
    print("precision:", [(p["net"].split("/")[-1], p["model"].split("-")[1], round(p["acc_fp16"], 3), p["bf16_flips"]) for p in o["precision"] if p["acc_fp16"] < 0.99 or p["bf16_flips"] > 0])
    print("trigger:", o["trigger"])
